"""Prepared V8+ W&B name mapping; not imported by the active V7 logger.

The mapping changes names only. V8 startup must explicitly integrate it with
tracking, journal deduplication, finalization markers and monitoring together.
"""

from functools import lru_cache
import json
from pathlib import Path
import re
from typing import Mapping


SCHEMA_PATH = Path(__file__).resolve().parents[3] / "configs/wandb-metric-schema-v2.json"


@lru_cache(maxsize=1)
def _schema():
    schema = json.loads(SCHEMA_PATH.read_text())
    if schema["schema_version"] != 2:
        raise ValueError("Expected W&B metric schema v2")
    return schema


def _performance_metric(name, schema):
    return (name in schema["performance_metrics"]
            or re.fullmatch(schema["performance_dynamic_pattern"], name) is not None)


def _render(scope, family, metric):
    if scope.startswith("test_"):
        return f"test/{family}_{scope[5:]}_{metric}"
    stage, prefix = ("val", "greedy_") if scope == "greedy" else (scope, "")
    if family in ("core", "reward"):
        return f"{stage}_{family}/{prefix}{metric}"
    return f"{stage}/{family}_{prefix}{metric}"


def _canonical(name, schema):
    section, separator, tail = name.partition("/")
    if not separator or section not in schema["panel_sections"]:
        return False
    if section.endswith(("_core", "_reward")):
        stage, family = section.split("_", 1)
        metric = tail
    else:
        stage = section
        family, separator, metric = tail.partition("_")
        if not separator or family not in schema["families"]:
            return False
        if stage != "test" and family in ("core", "reward"):
            return False
    scope = stage
    if stage == "val" and metric.startswith("greedy_"):
        scope, metric = "greedy", metric[len("greedy_"):]
    elif stage == "test":
        match = re.fullmatch(r"(initial|best|final)_(sampled|greedy)_(.+)", metric)
        if match is None:
            return False
        checkpoint, mode, metric = match.groups()
        scope = f"test_{checkpoint}_{mode}"
    if family == "performance":
        return scope == "train" and _performance_metric(metric, schema)
    if any(spec["family"] == family and spec["name"] == metric
           for spec in schema["base_metrics"].values()):
        return True
    if scope not in ("train", "val"):
        return False
    if any(spec["family"] == family and spec["name"] == metric
           for spec in schema["special_metrics"].values()):
        return True
    return (family == "optimization" and scope == "train"
            and (metric in {"adam_" + item for item in schema["adam_optimization_metrics"]}
                 or metric in {"ppo_" + item for item in schema["ppo_optimization_metrics"]}))


def metric_name_v2(name: str) -> str:
    """Map a v1/internal field to stage-first v2, or validate an existing v2 field.

    Unknown fields fail explicitly instead of silently creating ungrouped charts.
    optimizer_step remains the reserved actual-Adam axis.
    """
    schema = _schema()
    if name == schema["axis"]["field"]:
        return name
    direct = {"progress/ppo_iterations": "train/ppo_iteration",
              "progress/sampled_decisions": "train/sampled_decisions"}
    name = direct.get(name, name)
    if _canonical(name, schema):
        return name
    head, separator, body = name.partition("/")
    if not separator:
        raise ValueError(f"Unclassified W&B metric: {name}")
    body = body.replace("/", "_")
    if head in ("rollout", "baseline", "eval", "time", "ppo_summary"):
        if head == "ppo_summary":
            head, body = "train", "ppo_" + body
        else:
            head = {"rollout": "train", "baseline": "val", "eval": "val",
                    "time": "system"}[head]
    # Old application fields used system/. V8 routes them to train/performance_*;
    # W&B's own hardware telemetry is generated by its SDK and is not remapped.
    if head == "system" and _performance_metric(body, schema):
        return _render("train", "performance", body)
    if head in ("train", "val", "greedy"):
        scope = head
        if head == "val" and body.startswith("greedy_"):
            scope, body = "greedy", body[len("greedy_"):]
    elif head == "test":
        match = re.fullmatch(r"(initial|best|final)_mixed_(sampled|greedy)_(.+)", body)
        if match is None:
            raise ValueError(f"Unclassified heldout metric: {name}")
        stage, mode, body = match.groups()
        scope = f"test_{stage}_{mode}"
    else:
        raise ValueError(f"Unclassified W&B metric: {name}")
    spec = schema["base_metrics"].get(body)
    if spec is None and scope in ("train", "val"):
        spec = schema["special_metrics"].get(body)
    if spec is None and scope == "train":
        if body in schema["adam_optimization_metrics"]:
            spec = {"family": "optimization", "name": "adam_" + body}
        elif body.startswith("ppo_") and body[4:] in schema["ppo_optimization_metrics"]:
            spec = {"family": "optimization", "name": body}
    if spec is None:
        raise ValueError(f"Unclassified W&B metric: {name}")
    return _render(scope, spec["family"], spec["name"])


def map_metric_payload_v2(values: Mapping[str, object]) -> dict[str, object]:
    """Rename keys without changing scalar values or paying rewards again."""
    result = {}
    for name, value in values.items():
        target = metric_name_v2(name)
        if target in result and result[target] != value:
            raise ValueError(f"Conflicting W&B metric aliases: {target}")
        result[target] = value
    return result
